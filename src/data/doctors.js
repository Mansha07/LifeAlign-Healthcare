export function getDoctorById(id) {
  return doctors.find(d => d.id === id);
}

export function getDoctorsByHospital(hospitalId) {
  return doctors.filter(d => d.hospital === hospitalId);
}

export function getDoctorsBySpecialty(specialtyId) {
  if (!specialtyId) return doctors;
  return doctors.filter(d => d.specialty === specialtyId);
}

export function filterDoctors({ specialty, hospital, city, experience, consultationType }) {
  const { hospitals: hospitalData } = require('./hospitals');
  return doctors.filter(d => {
    if (specialty && d.specialty !== specialty) return false;
    if (hospital && d.hospital !== hospital) return false;
    if (consultationType && !d.consultationType.includes(consultationType)) return false;
    if (experience) {
      if (experience === '5-10' && (d.experience < 5 || d.experience > 10)) return false;
      if (experience === '10-15' && (d.experience < 10 || d.experience > 15)) return false;
      if (experience === '15+' && d.experience < 15) return false;
    }
    return true;
  });
}
